import { readFile, writeFile } from "node:fs/promises";
import { Script } from "node:vm";

const root = new URL("./", import.meta.url);
const tokens = JSON.parse(await readFile(new URL("../tokens/aureform.tokens.json", root), "utf8"));
const backend = await readFile(new URL("./backend.js", root), "utf8");
const entry = await readFile(new URL("./entry.js", root), "utf8");
const source = `/* Aureform UI · Apache-2.0. Generated by build.mjs; no network or credentials. */\nconst AUREFORM_TOKENS = ${JSON.stringify(tokens)};\n${backend}\n${entry}\n`;
new Script(source, { filename: "aureform-design-rebuild/code.js" });
await writeFile(new URL("./code.js", root), source);
console.log("Built the local Figma plugin with supplied tokens and three native starter families.");
